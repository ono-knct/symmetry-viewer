"""Reconstruct Halite from the recorded COD download.

Download 1000041.cif from https://www.crystallography.net/cod/
into a separate directory, then run with --source-dir DIR. The recorded hashes
prevent an unnoticed COD revision from changing the teaching examples. This
writer intentionally avoids CifWriter refinement and preserves source axes.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

try:
    import _bootstrap  # noqa: F401
except ModuleNotFoundError:
    from tools import _bootstrap  # noqa: F401

from pymatgen.io.cif import CifFile

SOURCES = {
    "Halite": ("1000041", "02d4f4fa315f7b97147256118acc7f9f20190d7246c3ea7209cfb8bd5d6e1fed", ("Na", "Cl")),
}


def reconstruct(name: str, source: Path) -> str:
    code, expected_hash, elements = SOURCES[name]
    if hashlib.sha256(source.read_bytes()).hexdigest() != expected_hash:
        raise ValueError(f"{source}: differs from the recorded 2026-10-12 download; review before updating")
    data = next(iter(CifFile.from_file(source).data.values())).data
    lines = [
        "# Generated by tools/reconstruct_cod_examples.py from a direct COD download.",
        f"# Source: https://www.crystallography.net/cod/{code}.cif (2026-10-12)",
        f"# Source SHA-256: {expected_hash}",
        "# Lattice and fractional sites retained; displacement parameters omitted.",
        "# Neutral element symbols and unit occupancies used for teaching.",
        "# See examples/SOURCES.md for attribution, processing and distribution terms.",
        f"data_{name}", f"_chemical_name '{name}'", f"_cod_database_code {code}",
        "_chemical_formula_sum 'Na Cl'",
    ]
    for key in ("_space_group_IT_number", "_symmetry_space_group_name_H-M", "_symmetry_space_group_name_Hall"):
        lines.append(f"{key} '{data[key]}'")
    for key in ("_cell_length_a", "_cell_length_b", "_cell_length_c", "_cell_angle_alpha", "_cell_angle_beta", "_cell_angle_gamma"):
        lines.append(f"{key} {data[key]}")
    lines += ["loop_", "_publ_author_name"] + [f"'{author}'" for author in data["_publ_author_name"]]
    for key in ("_journal_name_full", "_journal_volume", "_journal_year", "_journal_page_first", "_journal_page_last", "_journal_paper_doi"):
        lines.append(f"{key} '{data[key]}'")
    ops = data.get("_symmetry_equiv_pos_as_xyz", data.get("_space_group_symop_operation_xyz"))
    lines += ["loop_", "_symmetry_equiv_pos_as_xyz"] + [f"'{op}'" for op in ops]
    lines += ["loop_", "_atom_site_label", "_atom_site_type_symbol", "_atom_site_fract_x", "_atom_site_fract_y", "_atom_site_fract_z", "_atom_site_occupancy"]
    for i, element in enumerate(elements):
        xyz = [data[key][i] for key in ("_atom_site_fract_x", "_atom_site_fract_y", "_atom_site_fract_z")]
        lines.append(" ".join([element, element, *xyz, "1"]))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "examples/cif")
    args = parser.parse_args()
    # Validate the source before writing the output file.
    outputs = {name: reconstruct(name, args.source_dir / f"{code}.cif") for name, (code, _, _) in SOURCES.items()}
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, text in outputs.items():
        path = args.output_dir / f"{name}.cif"
        path.write_text(text, encoding="utf-8")
        print(path)


if __name__ == "__main__":
    main()
